"""Exports model.joblib as JSON for the Prediction page, which runs the model in the browser (Frontend/forecast.js).

Run after training.py:  python export_js.py
Writes Frontend/public/data/model.json. Each model is a gradient-boosted sum of decision trees:
  raw = base + learning_rate * sum(tree outputs);  stress probability = 1 / (1 + exp(-raw))
A tree node goes left when the feature value (as float32, like scikit-learn) is <= its threshold.
"""

import json
from pathlib import Path

import joblib
import numpy as np

import features as ft

HERE = Path(__file__).parent
MODEL_PATH = HERE / "model.joblib"
OUT = HERE.parent / "Frontend" / "public" / "data" / "model.json"


def tree_json(tree):
    t = tree.tree_
    return {
        "feature": t.feature.tolist(),
        "threshold": t.threshold.tolist(),
        "left": t.children_left.tolist(),
        "right": t.children_right.tolist(),
        "value": [round(float(v), 8) for v in t.value[:, 0, 0]],
    }


def model_json(model, n_features):
    # The model's starting value before any tree, taken from scikit-learn itself so it matches any init/loss
    base = float(model._raw_predict_init(np.zeros((1, n_features), dtype=np.float32))[0, 0])
    return {
        "base": base,
        "learning_rate": model.learning_rate,
        "trees": [tree_json(est[0]) for est in model.estimators_],
    }


def main():
    bundle = joblib.load(MODEL_PATH)
    columns = bundle["columns"]
    out = {
        "note": "Generated by Prediction-Training/export_js.py from model.joblib. Do not edit.",
        "columns": columns,
        "horizon_minutes": bundle["horizon_minutes"],
        "stress_window_minutes": bundle["stress_window_minutes"],
        # Feature settings from features.py, so the page builds exactly the same features
        "step_minutes": ft.STEP_MIN,
        "lag_minutes": ft.LAG_MIN,
        "pressure_trend_minutes": ft.PRESSURE_TREND_MIN,
        "min_rows": ft.MIN_ROWS,
        "interpolate_limit": 3,
        "models": {k: model_json(m, len(columns)) for k, m in bundle["models"].items()},
    }
    OUT.write_text(json.dumps(out, separators=(",", ":")), encoding="utf-8")
    print(f"Saved {OUT.relative_to(HERE.parent)} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
